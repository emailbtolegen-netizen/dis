import test from 'node:test';
import assert from 'node:assert/strict';
import { expandHouses } from '../src/domain/addressList.ts';

const h = (raw: string, def: string | null = null) => expandHouses(raw, def).houses;

test('списки домов из перечней дворов', () => {
  assert.deepEqual(h('Авангард-4 №3,4'), ['Авангард-4, 3', 'Авангард-4, 4']);
  assert.deepEqual(h('Авангард-2 21/22'), ['Авангард-2, 21', 'Авангард-2, 22']);
  assert.deepEqual(h('Абилхайр хан 70/1'), ['Абилхайр хан, 70/1']);
  assert.deepEqual(h('Датов №35А, №35Б В Г'), ['Датов, 35А', 'Датов, 35Б', 'Датов, 35В', 'Датов, 35Г']);
  assert.deepEqual(h('Атамбаев №68№68Б '), ['Атамбаев, 68', 'Атамбаев, 68Б']);
  assert.deepEqual(h('Өтемісұлы №9-Абай №95,97А'), ['Өтемісұлы, 9', 'Абай, 95', 'Абай, 97А']);
  assert.deepEqual(h('Өтемісов №116 және Абай №11'), ['Өтемісов, 116', 'Абай, 11']);
  assert.deepEqual(h('Вокзал-5 №1,7,7,9'), ['Вокзал-5, 1', 'Вокзал-5, 7', 'Вокзал-5, 9']);
  assert.deepEqual(h('Нурсая №1-9').length, 9);
  assert.deepEqual(h('мкр.Нурсая, ул.Т.Жумагалиева д № 21, 25-25А'), ['ул.Т.Жумагалиева, 21', 'ул.Т.Жумагалиева, 25', 'ул.Т.Жумагалиева, 25А']);
  assert.deepEqual(h('мкр.Привокзальный 5, дом№27,32'), ['мкр.Привокзальный-5, 27', 'мкр.Привокзальный-5, 32']);
  assert.deepEqual(h('мкр.Авангард 4мкр дом№14'), ['мкр.Авангард-4, 14']);
  assert.deepEqual(h('ул.Шманова дом №87, 1-2 блок'), ['ул.Шманова, 87']);
  assert.deepEqual(h('Курмангазы 1, 1 а'), ['Курмангазы, 1', 'Курмангазы, 1А']);
  assert.deepEqual(h('Кулманова №1А (ЖК Гранд Атырау) только деткий и освешение'), ['Кулманова, 1А']);
  assert.deepEqual(h('Химиетер поселкесі, Вольная кошесі'), []);
  assert.deepEqual(h('мкр.СМП-163, дом № 3,5,5в'), ['мкр.СМП-163, 3', 'мкр.СМП-163, 5', 'мкр.СМП-163, 5В']);
});

test('строки адресов лота с улицей по умолчанию', () => {
  assert.deepEqual(h('дома № 163,165,167 (0,61 га)', 'проспект Азаттык'), ['проспект Азаттык, 163', 'проспект Азаттык, 165', 'проспект Азаттык, 167']);
  assert.equal(h('дома №27-33 (2,8 га)', 'мкр.Алмагуль').length, 7);
  assert.deepEqual(h('ул. Сатпаева, д.24,26,28 (0,55 га)'), ['ул. Сатпаева, 24', 'ул. Сатпаева, 26', 'ул. Сатпаева, 28']);
});
